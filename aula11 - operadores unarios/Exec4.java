public class Exec4 {
	public static void main(String[] args) {
		// Precedência de Operadores Atribuição

		int numero = 5;
		++numero;

		System.out.println("O valor é: " + numero);

		numero++;
		System.out.println("O valor é: " + numero);

		--numero;
		System.out.println("O valor é: " + numero);

		numero--;
		System.out.println("O valor é: " + numero);
		
	}
}